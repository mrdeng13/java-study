def build():
    items = []
    seq = 0

    added = set()

    def add(name, cat, rarity, icon, desc, extra=None):
        nonlocal seq
        key = (cat, name)
        if key in added:          # 同名同类别去重（名单里跨档重复时保留高档）
            return
        added.add(key)
        seq += 1
        it = {
            "id": "s%05d" % seq,
            "name": name,
            "category": cat,
            "rarity": rarity,
            "icon": icon,
            "desc": desc,
        }
        if extra:
            it.update(extra)
        items.append(it)

    # ---- 武将 ----
    for n in REAL_T5:
        add(n, "general", 5, GENERAL_ICON[5], "%s —— 威震一方的顶级名将，得之可安天下。" % n)
    for n in REAL_T4:
        add(n, "general", 4, GENERAL_ICON[4], "%s —— 独当一面的宿将，军中柱石。" % n)
    for n in REAL_T3:
        add(n, "general", 3, GENERAL_ICON[3], "%s —— 久经沙场的将领，可堪一用。" % n)
    # 部曲编制组合（2★ / 1★ 填充）
    combos2 = ["%s·%s" % (u, r) for u in UNITS for r in RANKS_2]
    combos1 = ["%s·%s" % (u, r) for u in UNITS for r in RANKS_1]
    for n in combos2[:240]:
        add(n, "general", 2, GENERAL_ICON[2], "%s —— 军中精锐，阵列中的可靠战力。" % n)
    for n in combos1[:280]:
        add(n, "general", 1, GENERAL_ICON[1], "%s —— 行伍根基，万丈高楼起于垒土。" % n)

    # ---- 宝物 ----
    for n in FAMOUS_RELIC:
        add(n, "relic", 5, RELIC_ICON[5], "%s —— 名动天下的神兵重器，藏之可镇门庭。" % n)
    combos = ["%s·%s" % (m, f) for m in MATERIALS for f in FORMS]
    for n in combos[:140]:
        add(n, "relic", 4, RELIC_ICON[4], "%s —— 名匠所铸，锋芒内敛。" % n)
    for n in combos[140:340]:
        add(n, "relic", 3, RELIC_ICON[3], "%s —— 军中常见之器，耐用称手。" % n)
    for n in combos[340:560]:
        add(n, "relic", 2, RELIC_ICON[2], "%s —— 制式装备，虽无奇处却不可或缺。" % n)
    for n in combos[560:760]:
        add(n, "relic", 1, RELIC_ICON[1], "%s —— 粗陋之器，胜在量足。" % n)

    # ---- 奇物 ----
    it_combo = ["%s%s" % (p, t) for p in ITEM_PREFIX for t in ITEM_TOPIC]
    for i, n in enumerate(it_combo[:60]):
        add(n, "item", 4, ITEM_ICON[4], "《%s》—— 系统梳理，读一遍胜过盲刷十题。" % n)
    for n in it_combo[60:110]:
        add(n, "item", 3, ITEM_ICON[3], "《%s》—— 要点齐备，考前速览尤佳。" % n)
    for n in it_combo[110:140]:
        add(n, "item", 2, ITEM_ICON[2], "《%s》—— 随手可翻的零散札记。" % n)
    for n in it_combo[140:155]:
        add(n, "item", 1, ITEM_ICON[1], "《%s》—— 边角料，聊胜于无。" % n)

    # ---- U 级极品（仅加热炉）----
    for n, d in U_HIDDEN:
        add(n, "general", 6, "👑", d, {"only": "furnace"})

    # ---- 唯一品质（仅加热炉，极低概率，唯一一张）----
    for n, d in UNIQUE:
        add(n, "general", 7, "🌸", d, {"only": "furnace", "unique": True})

    # ---- 打福利标记 ----
    by_name = {}
    for it in items:
        by_name.setdefault(it["name"], []).append(it)
    for n in WELFARE_GENERALS + WELFARE_RELICS:
        for it in by_name.get(n, []):
            it["welfare"] = True

    # ---- 羁绊：名称 → id ----
    bonds = []
    for i, (bname, members, reward) in enumerate(BONDS, start=1):
        ids, missing = [], []
        for m in members:
            if m in by_name:
                ids.append(by_name[m][0]["id"])
            else:
                missing.append(m)
        if missing:
            print("  [warn] 羁绊「%s」缺少成员：%s" % (bname, "、".join(missing)))
        bonds.append({"id": "b%03d" % i, "name": bname,
                      "members": ids, "memberNames": members,
                      "reward": reward * BOND_REWARD_SCALE})

    return items, bonds


